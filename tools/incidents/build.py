"""HiBot incident knowledge builder: extraction + Jira XML enrichment + similarity + recurring groups.

    set PYTHONIOENCODING=utf-8
    python tools/incidents/build.py [--dataset PATH] [--jira-dir DIR] [--out DIR] [--codemap DIR]

Deterministic (no timestamps, sorted iteration). Python 3 stdlib only.
"""
import argparse
import os
import re
import sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import extract as ex  # noqa: E402
import jira_xml  # noqa: E402
import similarity as sim  # noqa: E402
from common import CODEMAP, DATASET, JIRA_RAW, OUT_DIR, dump_json, load_json, pseudonym  # noqa: E402

REPORTER_HINT_MIN = 3
REPORTER_HINT_SHARE = 0.7


# Custom fields that carry personal data or are generic ITSM form boilerplate are dropped (see README).
CF_DROP = re.compile(r"(?i)(user ?name|full name|display name|e-?mail|phone|mobile|reporter|creator|requester|"
                     r"\btitle\b|message|\bmf\d|form |tempo|visio|sla|rank|sub-task|selected customer|manager|employee)")
CF_MAX_VALUE = 300


def enrich_from_jira(rec, jira, persons_re):
    """Merge a parsed Jira XML issue into the ticket record (full description, comments, resolution, ...)."""
    comments = []
    for c in jira["comments"]:
        text = ex.scrub(c["text"], persons_re)
        if text:   # empty comments (attachment-only / bot) are skipped
            comments.append({"author": pseudonym(c["author"], "U"), "created": c["created"], "text": text})
    custom = {}
    for k, vs in sorted(jira["custom_fields"].items()):
        if CF_DROP.search(k):
            continue
        vals = [ex.scrub(v, persons_re) for v in vs if len(v) <= CF_MAX_VALUE]
        if vals:
            custom[k] = vals
    return {
        "jira_enriched": True,
        "resolution": jira["resolution"] or None, "resolved": jira["resolved"] or None, "updated": jira["updated"] or None,
        "issue_type": jira["type"] or None,
        "components": jira["components"], "labels": jira["labels"],
        "custom_fields": custom,
        "comments": comments,
    }


def group_stats(members, recs, sim_rows, gid):
    """Summary dict of one recurring group."""
    def dom(vals):
        c = Counter(v for v in vals if v)
        if not c:
            return None
        top = sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))[:3]
        return {"value": top[0][0], "share": round(top[0][1] / len(members), 2),
                "distribution": {k: v for k, v in top}}
    best, best_s = members[0], -1.0
    for i in members:
        s = sum(sim_rows[i].get(j, 0.0) for j in members if j != i)
        if s > best_s + 1e-12:
            best, best_s = i, s
    created = sorted(recs[i]["created"] for i in members if recs[i]["created"])
    terms = Counter()
    for i in members:
        terms.update(set(recs[i]["_tokens"]))
    top_terms = [t for t, c in sorted(terms.items(), key=lambda kv: (-kv[1], kv[0]))
                 if not t.startswith("<") and "_" not in t and c >= max(2, len(members) * 0.5)][:8]
    return {
        "group_id": gid, "size": len(members), "keys": [recs[i]["key"] for i in sorted(members, key=lambda i: recs[i]["key"])],
        "representative_key": recs[best]["key"], "representative_title": recs[best]["text_clean"]["summary"],
        "dominant_problem_type": dom([recs[i]["problem_type"] for i in members]),
        "dominant_app": dom([recs[i]["app_guess"] for i in members]),
        "dominant_country": dom([recs[i]["country"] for i in members]),
        "first_seen": created[0] if created else None, "last_seen": created[-1] if created else None,
        "avg_internal_similarity": round(sum(sim_rows[i].get(j, 0.0) for i in members for j in members if i != j)
                                         / max(1, len(members) * (len(members) - 1)), 3),
        "common_terms": top_terms,
        "with_work_order_pct": round(100.0 * sum(1 for i in members if recs[i]["entities"]["work_order_ids"]) / len(members), 1),
    }


def pct(a, b):
    return "%.1f%%" % (100.0 * a / b) if b else "n/a"


def write_stats(path, recs, groups, jira_n, params):
    n = len(recs)
    L = ["# Incident corpus statistics", "", "Generated by `tools/incidents/build.py` (deterministic).", "",
         "- tickets: **%d**; enriched from Jira XML: **%d** (%s)" % (n, jira_n, pct(jira_n, n)),
         "- tickets with >=1 work order id: **%s** (strong keyword evidence: %s)" % (
             pct(sum(1 for r in recs if r["entities"]["work_order_ids"]), n),
             pct(sum(1 for r in recs if r["entities"]["work_order_ids_strong"]), n)),
         "- tickets with >=1 SKU/model/material code: %s" % pct(sum(1 for r in recs if r["entities"]["sku_codes"] or r["entities"]["material_codes"]), n),
         "- tickets with a country: %s" % pct(sum(1 for r in recs if r["country"]), n),
         "- tickets with >=1 error text: %s" % pct(sum(1 for r in recs if r["entities"]["error_texts"]), n),
         "- Sirius-app tickets (portal/crm/partner/technician/sirius_unknown): %d" % sum(1 for r in recs if r["app_guess"] in ("portal", "crm", "partner", "technician", "sirius_unknown")),
         "- Sirius-app tickets with a screen hint: %s" % pct(
             sum(1 for r in recs if r["app_guess"] in ("portal", "crm", "partner", "technician") and r["screen_hints"]),
             sum(1 for r in recs if r["app_guess"] in ("portal", "crm", "partner", "technician"))),
         "- all tickets with a screen hint: %s" % pct(sum(1 for r in recs if r["screen_hints"]), n),
         "- recurring groups (size>=2): **%d** covering %d tickets (%s); largest %d; singletons %d" % (
             len(groups), sum(g["size"] for g in groups), pct(sum(g["size"] for g in groups), n),
             groups[0]["size"] if groups else 0, n - sum(g["size"] for g in groups)),
         "- thresholds: edge_min=%s, group_threshold=%s" % (params["edge_min"], params["group_threshold"]), ""]

    def table(title, counter, total):
        L.append("## " + title)
        L.append("")
        L.append("| value | tickets | share |")
        L.append("|---|---:|---:|")
        for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0]))):
            L.append("| %s | %d | %s |" % (k, v, pct(v, total)))
        L.append("")
    table("problem_type", Counter(r["problem_type"] for r in recs), n)
    table("app_guess", Counter(r["app_guess"] for r in recs), n)
    table("country (top 25, None = undetected)", Counter(dict(Counter(str(r["country"]) for r in recs).most_common(25))), n)
    table("language", Counter(r["language"] for r in recs), n)
    L.append("## Top 30 recurring groups")
    L.append("")
    L.append("| group | size | representative title | problem_type | app | country | first | last |")
    L.append("|---|---:|---|---|---|---|---|---|")
    for g in groups[:30]:
        t = g["representative_title"].replace("|", "/").replace("\n", " ")[:80]
        L.append("| %s | %d | %s | %s | %s | %s | %s | %s |" % (
            g["group_id"], g["size"], t, g["dominant_problem_type"]["value"] if g["dominant_problem_type"] else "",
            g["dominant_app"]["value"] if g["dominant_app"] else "", g["dominant_country"]["value"] if g["dominant_country"] else "-",
            (g["first_seen"] or "")[:10], (g["last_seen"] or "")[:10]))
    L.append("")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default=DATASET)
    ap.add_argument("--jira-dir", default=JIRA_RAW)
    ap.add_argument("--out", default=OUT_DIR)
    ap.add_argument("--codemap", default=CODEMAP)
    ap.add_argument("--edge-min", type=float, default=sim.EDGE_MIN)
    ap.add_argument("--group-threshold", type=float, default=sim.GROUP_THRESHOLD)
    a = ap.parse_args(argv)

    tickets = load_json(a.dataset)["tickets"]
    tickets.sort(key=lambda t: t["key"])
    names = set()
    for t in tickets:
        names.add(t.get("reporter") or "")
        names.add(t.get("assignee") or "")
    jira = jira_xml.load_dir(a.jira_dir)
    for j in jira.values():
        names.add(j["reporter"]); names.add(j["assignee"])
        for c in j["comments"]:
            names.add(c["author"])
    matcher = ex.ScreenMatcher(a.codemap)
    extractor = ex.Extractor(sorted(n for n in names if n), matcher)
    persons_re = extractor.persons_re
    if matcher.ok:   # corpus document frequencies of known UI phrases (down-weights generic phrases)
        matcher.fit([(jira[t["key"]]["summary"] + " " + jira[t["key"]]["description"]) if t["key"] in jira
                     else t["summary"] + " " + t.get("desc", "") for t in tickets])

    recs = []
    for t in tickets:
        j = jira.get(t["key"])
        desc = j["description"] if j and j["description"] else t.get("desc", "")
        summary = j["summary"] if j and j["summary"] else t["summary"]
        r = extractor.extract(t, summary=summary, desc=desc)
        rec = {
            "key": t["key"], "link": t.get("link"), "status": t.get("status"), "priority": t.get("priority"),
            "created": t.get("created"), "service": t.get("service"), "sub_service": t.get("sub_service"),
            "reporter_id": pseudonym(t.get("reporter"), "R"), "assignee_id": pseudonym(t.get("assignee"), "A"),
            "text_clean": r["text_clean"], "desc_truncated": not (j and j["description"]),
            "entities": r["entities"], "country": r["country"]["country"], "countries": r["country"]["countries"],
            "country_region": r["country"]["country_region"], "company_code": r["country"]["company_code"],
            "country_source": r["country"]["country_source"],
            "app_guess": r["app"]["app_guess"], "app_source": r["app"]["app_source"], "app_text_hint": r["app"]["app_text_hint"],
            "language": r["language"]["language"], "languages": r["language"]["languages"],
            "problem_type": r["problem"]["problem_type"], "problem_confidence": r["problem"]["problem_confidence"],
            "problem_rule": r["problem"]["problem_rule"], "problem_scores": r["problem"]["problem_scores"],
            "screen_hints": r["screen_hints"],
        }
        if j:
            rec.update(enrich_from_jira(rec, j, persons_re))
            cc = (rec["custom_fields"].get("Country Code") or [""])[0].strip().upper()
            if not rec["country"] and re.fullmatch(r"[A-Z]{2}", cc):   # Jira custom field beats the reporter hint
                rec["country"], rec["countries"], rec["country_source"] = cc, [cc], "jira_custom_field"
            ctext = "\n".join(c["text"] for c in rec["comments"])
            rec["comment_entities"] = {k: v for k, v in ex.extract_ids(ctext).items() if v}
        else:
            rec["jira_enriched"] = False
        rec["_tokens"] = None
        recs.append(rec)

    # reporter hint for country (data driven; only fills tickets without any other evidence)
    by_rep = defaultdict(Counter)
    for r in recs:
        if r["country"] and r["country_source"] in ("title", "desc") and r["reporter_id"]:
            by_rep[r["reporter_id"]][r["country"]] += 1
    for r in recs:
        if not r["country"] and not r["countries"] and r["reporter_id"] in by_rep:
            c = by_rep[r["reporter_id"]]
            tot = sum(c.values())
            top, cnt = sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))[0]
            if tot >= REPORTER_HINT_MIN and cnt / tot >= REPORTER_HINT_SHARE and r["app_guess"] in ("portal", "crm", "partner", "technician", "sirius_unknown"):
                r["country"], r["countries"], r["country_source"] = top, [top], "reporter_hint"

    # similarity + groups
    doc_tokens = []
    for r in recs:
        s, d = r["text_clean"]["summary"], r["text_clean"]["desc"]
        toks = sim.tokenize(s, bigrams=True) * 2 + sim.tokenize(d)
        r["_tokens"] = toks
        doc_tokens.append(toks)
    similar, groups_idx, sim_rows = sim.similar_and_groups(doc_tokens, 5, a.edge_min, a.group_threshold)
    groups = []
    for gi, members in enumerate([g for g in groups_idx if len(g) >= 2], 1):
        gid = "G%03d" % gi
        groups.append(group_stats(members, recs, sim_rows, gid))
        for i in members:
            recs[i]["group_id"] = gid
    for i, r in enumerate(recs):
        r.setdefault("group_id", None)
        r["similar"] = [{"key": recs[j]["key"], "score": s} for j, s in similar[i]]
        del r["_tokens"]

    dump_json(os.path.join(a.out, "tickets_enriched.json"), {"meta": {
        "count": len(recs), "jira_enriched": sum(1 for r in recs if r["jira_enriched"]),
        "edge_min": a.edge_min, "group_threshold": a.group_threshold,
        "note": "raw reporter/assignee names, raw summary/desc are not stored; see README.md"}, "tickets": recs})
    dump_json(os.path.join(a.out, "groups.json"), {"meta": {"count": len(groups), "edge_min": a.edge_min,
                                                           "group_threshold": a.group_threshold}, "groups": groups})
    write_stats(os.path.join(a.out, "stats.md"), recs, groups, sum(1 for r in recs if r["jira_enriched"]),
                {"edge_min": a.edge_min, "group_threshold": a.group_threshold})
    print("tickets=%d jira_enriched=%d groups=%d (covering %d tickets)" % (
        len(recs), sum(1 for r in recs if r["jira_enriched"]), len(groups), sum(g["size"] for g in groups)))


if __name__ == "__main__":
    main()
